/**
 * Search the master library and active program for matching exercises.
 */
export function searchExercises(query: string, muscleFilter?: MuscleGroup | 'all'): ExerciseTemplate[] {
  const cleanQ = query.trim().toLowerCase();

  return MASTER_EXERCISE_LIBRARY.filter(ex => {
    const matchesQuery = !cleanQ || 
      ex.name.toLowerCase().includes(cleanQ) || 
      ex.primaryMuscle.toLowerCase().includes(cleanQ) ||
      ex.equipment.toLowerCase().includes(cleanQ);

    const matchesMuscle = !muscleFilter || muscleFilter === 'all' || ex.primaryMuscle === muscleFilter;

    return matchesQuery && matchesMuscle;
  });
}

/**
 * Creates a unique Exercise instance with ID, order, and workoutDayId.
 */
export function createExerciseInstance(
  template: Partial<ExerciseTemplate> & { name: string; primaryMuscle: MuscleGroup },
  workoutDayId: string | number,
  order: number
): Exercise {
  const id = `ex-${Date.now()}-${Math.random().toString(36).substr(2, 5)}`;

  return {
    id,
    workoutDayId,
    name: template.name,
    order,
    targetSets: template.targetSets || 3,
    targetRepMin: template.targetRepMin || 8,
    targetRepMax: template.targetRepMax || 12,
    specialInstruction: template.specialInstruction || '',
    primaryMuscle: template.primaryMuscle,
    secondaryMuscles: template.secondaryMuscles || [],
    equipment: template.equipment || 'dumbbell',
    movementPattern: template.movementPattern || 'isolation',
    isCompound: template.isCompound ?? false,
    isIsolation: template.isIsolation ?? true,
    isFailureBased: template.isFailureBased ?? false,
    defaultWeightKg: template.defaultWeightKg || 20,
    weightIncrementKg: template.weightIncrementKg || 2.5,
  };
}
